CREATE TABLE Payment(
  Id INT IDENTITY(1, 1) PRIMARY KEY,
  Name NVARCHAR(50) NOT NULL UNIQUE,
  CreatedAt DATETIME2 DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME2 DEFAULT NULL
);

CREATE TABLE Food(
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Name NVARCHAR(100) NOT NULL UNIQUE,
  Price DECIMAL(19,4) NOT NULL,
  Stock INT NOT NULL,
  CreatedAt DATETIME2 DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME2 DEFAULT NULL,

  CONSTRAINT CK_Food_Stock CHECK(Stock >= 0)
);

CREATE TABLE Orders(
  Id INT IDENTITY(1,1) PRIMARY KEY,
  OrderId INT NOT NULL,
  TotalAmount DECIMAL(19,4) NOT NULL,
  PaymentMethodId INT NOT NULL,
  CreatedAt DATETIME2 DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME2 DEFAULT NULL,

  INDEX IX_Orders_OrderId (OrderId),
  CONSTRAINT FK_Orders_Payment FOREIGN KEY(PaymentMethodId) REFERENCES Payment(Id),
  INDEX IX_Orders_PaymentMethodId (PaymentMethodId)
);

CREATE TABLE Cart(
  Id INT IDENTITY(1, 1) PRIMARY KEY,
  CartId INT NOT NULL UNIQUE,
  OrderId INT NOT NULL,
  CreatedAt DATETIME2 DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME2 DEFAULT NULL
);

CREATE TABLE CartItem(
  Id INT IDENTITY(1, 1) PRIMARY KEY,
  FoodId INT NOT NULL,
  CartId INT NOT NULL,
  Qty INT NOT NULL,
  CreatedAt DATETIME2 DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME2 DEFAULT NULL,

  CONSTRAINT CK_CartItem_Qty CHECK(Qty > 0),
  CONSTRAINT FK_CartItem_Food FOREIGN KEY(FoodId) REFERENCES Food(Id),
  CONSTRAINT FK_CartItem_Cart FOREIGN KEY(CartId) REFERENCES Cart(Id),
  INDEX IX_CartItem_CartId (CartId),
  INDEX IX_CartItem_FoodId (FoodId)
);

CREATE TABLE OrderItem(
  Id INT IDENTITY(1, 1) PRIMARY KEY,
  OrderId INT NOT NULL,
  FoodId INT NOT NULL,
  Price DECIMAL(19,4) NOT NULL, 
  CreatedAt DATETIME2 DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME2 DEFAULT NULL,

  CONSTRAINT FK_OrderItem_Food FOREIGN KEY(FoodId) REFERENCES Food(Id),
  CONSTRAINT FK_OrderItem_Orders FOREIGN KEY(OrderId) REFERENCES Orders(Id),
  INDEX IX_OrderItem_OrderId (OrderId),
  INDEX IX_OrderItem_FoodId (FoodId)
);
